"""Research-only, cooperative scheduling of measured candidate verification.

This module is not wired into the production runtime. Scores are replacements
from the existing verifier, never generated by the scheduling heuristic.
"""

from __future__ import annotations

import copy
import math
import time
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, replace
from typing import Any, Literal

from src.query.translator import QueryProcessing
from src.retrieval.color_filter import AdvancedKISReranker
from src.retrieval.fusion import canonical_key

EvidenceKind = Literal["geometry", "full"]


@dataclass(frozen=True)
class VerificationOutcome:
    """A complete action may replace one candidate, including its evidence."""

    candidate: dict[str, Any]
    complete: bool
    reason: str


class ExistingEvidenceVerifier:
    """Reuse existing geometry/HSV semantics on an isolated candidate copy.

    Full verification includes geometry again so instance assignments stay
    consistent. It replaces the geometry-only score instead of adding twice.
    All frame/object/image I/O happens inside the timed action.
    """

    def __init__(self, verifier: AdvancedKISReranker, processing: QueryProcessing) -> None:
        self.verifier = verifier
        self.processing = processing

    def __call__(self, candidate: dict[str, Any], kind: EvidenceKind) -> VerificationOutcome:
        processing = self.processing
        if processing.decomposition is None:
            return VerificationOutcome(candidate, False, "constraints_missing")
        if kind == "geometry":
            decomposition = replace(
                processing.decomposition, color_constraints=(),
                negation_constraints=tuple(
                    c for c in processing.decomposition.negation_constraints if c.color is None
                ),
            )
            processing = replace(processing, decomposition=decomposition)
        output = self.verifier(processing, [copy.deepcopy(candidate)])
        diagnostic = self.verifier.last_diagnostics
        state = str(diagnostic.get("state", "unknown"))
        complete = state == "ready"
        return VerificationOutcome(output[0] if complete else candidate, complete, state)


def requested_evidence(processing: QueryProcessing) -> tuple[EvidenceKind, ...]:
    """Request only evidence types that can address bound query constraints."""

    decomposition = processing.decomposition
    if decomposition is None:
        return ()
    kinds: list[EvidenceKind] = []
    geometry = (*decomposition.spatial_constraints, *decomposition.relative_constraints,
                *(c for c in decomposition.negation_constraints if c.color is None))
    color = (*decomposition.color_constraints,
             *(c for c in decomposition.negation_constraints if c.color is not None))
    if any(c.bound for c in geometry):
        kinds.append("geometry")
    if any(c.bound for c in color):
        kinds.append("full")
    return tuple(kinds)


def rank_disagreement(candidate: Mapping[str, Any]) -> float:
    """Bounded spread of observed ranks; missing channels imply no disagreement."""

    values = [float(v) for v in candidate.get("channel_ranks", {}).values()
              if isinstance(v, (int, float)) and not isinstance(v, bool)
              and math.isfinite(v) and v >= 1]
    if len(values) < 2:
        return 0.0
    return (max(values) - min(values)) / max(values)


class BudgetedEvidenceReranker:
    """Compare rank-first and cost-aware anytime verification, with explicit overruns.

    A started action cannot be interrupted. Its completed result is retained even
    when it overruns; no further action starts. This is not a hard latency bound.
    Cost estimates are fixed inputs, not fitted from test outcomes.
    """

    VERSION = "research-evidence-budget-v1"

    def __init__(
        self, *, budget_ms: float, candidate_depth: int = 20,
        policy: Literal["rank", "cost_aware"] = "cost_aware",
        estimated_cost_ms: Mapping[EvidenceKind, float] | None = None,
        clock: Callable[[], float] = time.perf_counter,
    ) -> None:
        if not math.isfinite(budget_ms) or budget_ms < 0:
            raise ValueError("budget_ms must be finite and nonnegative")
        if not 1 <= candidate_depth <= 100:
            raise ValueError("candidate_depth must be in [1, 100]")
        if policy not in {"rank", "cost_aware"}:
            raise ValueError("unsupported budget policy")
        costs = dict(estimated_cost_ms or {"geometry": 10.0, "full": 100.0})
        if set(costs) != {"geometry", "full"} or any(
            not math.isfinite(v) or v <= 0 for v in costs.values()
        ):
            raise ValueError("positive finite estimates are required for both action types")
        self.budget_ms = float(budget_ms)
        self.candidate_depth = candidate_depth
        self.policy = policy
        self.costs = costs
        self.clock = clock

    def run(
        self, candidates: Sequence[dict[str, Any]], kinds: Sequence[EvidenceKind],
        verify: Callable[[dict[str, Any], EvidenceKind], VerificationOutcome],
    ) -> tuple[list[dict[str, Any]], dict[str, Any]]:
        """Run bounded work; preserve every input identity and unverified score."""

        started = self.clock()
        original = copy.deepcopy(list(candidates))
        keys = [canonical_key(c) for c in original]
        if len(set(keys)) != len(keys):
            raise ValueError("candidate identities must be unique")
        if any(not math.isfinite(float(c.get("score", 0))) for c in original):
            raise ValueError("candidate scores must be finite")
        kinds = tuple(dict.fromkeys(kinds))
        if set(kinds) - {"geometry", "full"}:
            raise ValueError("unknown evidence type")
        output = copy.deepcopy(original)
        depth = min(len(original), self.candidate_depth)
        if self.policy == "rank":
            # Fixed baseline performs the fullest applicable action per rank.
            jobs = [(i, "full" if "full" in kinds else "geometry")
                    for i in range(depth)] if kinds else []
        else:
            jobs = [(i, kind) for i in range(depth) for kind in kinds]
        trace: list[dict[str, Any]] = []
        completed = 0
        reason = "no_constraints" if not kinds else "exhausted_actions"
        while jobs:
            elapsed = (self.clock() - started) * 1000
            remaining = self.budget_ms - elapsed
            if remaining <= 0:
                reason = "budget_exhausted"
                break
            feasible = [(i, kind) for i, kind in jobs if self.costs[kind] <= remaining]
            if not feasible:
                reason = "no_estimated_action_fits"
                break
            if self.policy == "rank":
                selected = jobs[0]
                if selected not in feasible:
                    reason = "next_rank_action_does_not_fit"
                    break
            else:
                # Heuristic priority, not a calibrated probability or expected gain.
                selected = min(feasible, key=lambda job: (
                    -(1.0 + rank_disagreement(original[job[0]]))
                    / ((job[0] + 1) * self.costs[job[1]]), job[0], job[1],
                ))
            index, kind = selected
            jobs.remove(selected)
            action_started = self.clock()
            record: dict[str, Any] = {
                "candidate_rank": index + 1, "identity": list(keys[index]), "kind": kind,
                "estimated_ms": self.costs[kind], "started_at_ms": elapsed,
            }
            try:
                result = verify(copy.deepcopy(original[index]), kind)
                valid = (canonical_key(result.candidate) == keys[index]
                         and math.isfinite(float(result.candidate.get("score", 0))))
                if result.complete and valid:
                    output[index] = copy.deepcopy(result.candidate)
                    completed += 1
                    if kind == "full":
                        jobs = [job for job in jobs if job[0] != index]
                record.update(complete=bool(result.complete and valid),
                              reason=result.reason if valid else "invalid_candidate_result")
            except Exception as error:
                record.update(complete=False, reason="verifier_error", error_type=type(error).__name__)
            record["elapsed_ms"] = (self.clock() - action_started) * 1000
            trace.append(record)
        # Keep base tie order; a no-op policy must return the original order.
        if completed:
            output = [item for _, item in sorted(enumerate(output),
                      key=lambda pair: (-float(pair[1].get("score", 0)), pair[0]))]
        elapsed = (self.clock() - started) * 1000
        return output, {
            "version": self.VERSION, "policy": self.policy, "budget_ms": self.budget_ms,
            "cost_estimates_ms": self.costs, "candidate_depth": self.candidate_depth,
            "elapsed_ms": elapsed, "overrun_ms": max(0.0, elapsed - self.budget_ms),
            "stop_reason": reason, "completed_actions": completed,
            "attempted_actions": len(trace), "trace": trace,
            "hard_deadline": False, "production_activation": False,
        }
